// sw.js — lets the app open without internet.
// "Network first": always tries to fetch the newest version from GitHub,
// and falls back to the saved copy when you're offline.
const CACHE = 'strik-v1';

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()));

self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  // "no-cache": always ask GitHub whether the file has changed, so the phone never mixes
  // a new app.js with an old style.css (GitHub Pages lets the browser keep files for 10 minutes).
  const fresh = e.request.mode === 'navigate'
    ? new Request(e.request.url, { cache: 'no-cache', credentials: 'same-origin' })
    : new Request(e.request, { cache: 'no-cache' });
  e.respondWith(
    fetch(fresh)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(e.request, copy));
        return res;
      })
      .catch(() => caches.match(e.request, { ignoreSearch: true }))
  );
});
